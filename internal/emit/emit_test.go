func TestEmit_NonNilableReturnUsesZeroValue(t *testing.T) {
	t.Parallel()

	// Return type = value struct (non-nilable). The provider chain must
	// include at least one (T, error) provider so writeSteps takes the
	// error branch and writes the zero-value return.
	src := `package myapp
type DB struct{}
type Bag struct{ DB *DB }
func NewDB() (*DB, error) { return nil, nil }
func NewBag(db *DB) Bag { return Bag{DB: db} }

//injector:container returns=Bag
type app struct {
	B Bag ` + "`inject:\"\"`" + `
}
`
	pkg := loadTestPackage(t, src)
	cs, dsC := scan.Containers([]*packages.Package{pkg})
	if diag.HasErrors(dsC) {
		t.Fatalf("scan.Containers: %v", dsC)
	}
	ps, dsP := scan.Providers([]*packages.Package{pkg})
	if diag.HasErrors(dsP) {
		t.Fatalf("scan.Providers: %v", dsP)
	}

	var target ir.Container
	for _, c := range cs {
		if c.StructName == "app" {
			target = c
			break
		}
	}
	idx := plan.NewIndex(ps)
	pl, dsB := plan.Build(target, idx, plan.Options{})
	if diag.HasErrors(dsB) {
		t.Fatalf("plan.Build: %v", dsB)
	}

	out, err := emit.Emit("myapp", []plan.Plan{pl})
	if err != nil {
		t.Fatalf("Emit: %v", err)
	}
	if !strings.Contains(string(out), "*new(Bag)") {
		t.Errorf("expected *new(Bag) zero-value return in error path, got:\n%s", out)
	}
}

func TestEmit_GeneratedCompiles(t *testing.T) {
	t.Parallel()

	src := `package myapp
type DB struct{}
type User struct{}
func NewDB() *DB { return nil }
func NewUser(db *DB) *User { return nil }
type Container struct {
	User *User ` + "`inject:\"\"`" + `
}
`
	p := buildPlan(t, src)
	out, err := emit.Emit("myapp", []plan.Plan{p})
	if err != nil {
		t.Fatalf("Emit: %v", err)
	}

	// Re-type-check the original source plus the generated file as a single
	// package to ensure the generated code is syntactically and semantically
	// valid Go.
	fset := token.NewFileSet()
	original, err := parser.ParseFile(fset, "myapp.go", src, parser.ParseComments)
	if err != nil {
		t.Fatalf("parse original: %v", err)
	}
	generated, err := parser.ParseFile(fset, "injector_gen.go", out, parser.ParseComments)
	if err != nil {
		t.Fatalf("parse generated: %v\n--- generated ---\n%s", err, out)
	}
	if _, err := (&types.Config{Importer: importer.Default()}).
		Check("myapp", fset, []*ast.File{original, generated}, nil); err != nil {
		t.Fatalf("type-check generated: %v\n--- generated ---\n%s", err, out)
	}
}

