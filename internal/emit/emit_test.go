// buildPlan runs scan + plan on src and returns the plan for the
// "Container" struct. Tests in this file all use that conventional name and
// default plan options.
func buildPlan(t *testing.T, src string) plan.Plan {
	t.Helper()
	const containerName = "Container"
	pkg := loadTestPackage(t, src)

	cs, dsC := scan.Containers([]*packages.Package{pkg})
	if diag.HasErrors(dsC) {
		t.Fatalf("scan.Containers: %v", dsC)
	}
	ps, dsP := scan.Providers([]*packages.Package{pkg})
	if diag.HasErrors(dsP) {
		t.Fatalf("scan.Providers: %v", dsP)
	}

	var target ir.Container
	for _, c := range cs {
		if c.StructName == containerName {
			target = c
			break
		}
	}
	if target.StructName == "" {
		t.Fatalf("container %q not found", containerName)
	}

	idx := plan.NewIndex(ps)
	pl, dsB := plan.Build(target, idx, plan.Options{})
	if diag.HasErrors(dsB) {
		t.Fatalf("plan.Build: %v", dsB)
	}
	return pl
}

func loadTestPackage(t *testing.T, src string) *packages.Package {
	t.Helper()
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "test.go", src, parser.ParseComments)
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	info := &types.Info{
		Types: make(map[ast.Expr]types.TypeAndValue),
		Defs:  make(map[*ast.Ident]types.Object),
		Uses:  make(map[*ast.Ident]types.Object),
	}
	pkg, err := (&types.Config{Importer: importer.Default()}).Check("myapp", fset, []*ast.File{f}, info)
	if err != nil {
		t.Fatalf("check: %v", err)
	}
	return &packages.Package{
		PkgPath:   "myapp",
		Name:      "myapp",
		Syntax:    []*ast.File{f},
		Types:     pkg,
		TypesInfo: info,
		Fset:      fset,
	}
}
